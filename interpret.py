def retry_block(violations: list) -> str:
    """게이트 위반 재생성용 꼬리 지시 — run_daily가 1차 위반 시 붙인다."""
    if not violations:
        return ""
    lines = "\n".join(f"- {v}" for v in violations)
    return (
        "\n\n[재작성 지시 — 발송 게이트 위반]\n"
        "직전 생성문이 아래 규칙을 위반해 폐기됐다. 같은 데이터로 처음부터 새로 쓰되,\n"
        "아래 위반 패턴을 절대 다시 쓰지 마라:\n" + lines
    )


def build_request(layers: dict, profile: dict, retry_note: list | None = None,
                  model: str = DEFAULT_MODEL) -> dict:
    """요청 본문(model·system·messages). 생성 파라미터(CREATE_KWARGS)는 generate가 붙인다."""
    return {
        "model": model,
        "system": profile["system"],
        "messages": [{"role": "user",
                      "content": build_prompt(layers, profile) + retry_block(retry_note or [])}],
    }


def daewoon_year_line(chart, year: int) -> str:
    """지금 대운이 시작한 해·끝나는 해와 올해가 그 몇 년째인지 — 해석문이 숫자를 직접 세다 틀리지 않게 코드가 센다.
    대운수가 반올림 경계면(birth.daewoon의 boundary) 시작 연도가 1년 앞뒤로 갈릴 수 있다는 말을 붙인다."""
    from birth import daewoon_now            # 점검 출력(me_config)·미리보기(birth)와 같은 셈

    now = daewoon_now(chart.DAEWOON_RANGES, year)
    if now is None:
        return "- 지금 대운: 대운표 범위 밖"
    _gj, start, end, nth = now
    s = (f"- 지금 대운: {start}년에 시작해 {end}년까지({end - start + 1}년) — 올해 {year}년은 그 "
         f"{nth}년째다. 몇 년째인지는 이 숫자를 그대로 써라(직접 세지 마라)")
    if (getattr(chart, "DAEWOON_INFO", None) or {}).get("boundary"):
        s += " · 대운수 반올림 경계라 시작 연도가 1년 앞뒤로 갈릴 수 있다"
    return s


# 호출 1회 시간 제한(초)과 SDK 자동 재시도 수. 정상 생성(수천 토큰)은 시간 제한보다 짧다. 멈춘 호출 하나는
# 최악 (1 + 재시도) × 제한 = 8분 안에 실패로 끝난다 — 작업 시간 제한(30분)에 걸려 '취소'되기 전에 실패해야
# 워크플로의 실패 알림 스텝이 돈다(SDK 기본값은 10분 × 3회라 한 사람만으로도 30분이 찬다).
CLIENT_TIMEOUT_S = 240.0
CLIENT_MAX_RETRIES = 1


def _client():
    import anthropic

    api_key = (os.environ.get("ANTHROPIC_API_KEY") or "").strip()   # 딸려 온 줄바꿈이 헤더 오류 문장에 실리지 않게
    if not api_key:
        raise RuntimeError("ANTHROPIC_API_KEY 환경변수가 필요합니다.")
    return anthropic.Anthropic(api_key=api_key, timeout=CLIENT_TIMEOUT_S, max_retries=CLIENT_MAX_RETRIES)


def _n(usage, name: str) -> int:
    try:
        return int(getattr(usage, name, 0) or 0)
    except (TypeError, ValueError):
        return 0


def generate(layers: dict, model: str = DEFAULT_MODEL, retry_note: list | None = None,
             profile: dict | None = None) -> str:
    """Claude 호출 1회 → 메시지 본문. 사용 토큰을 로그 한 줄로 남긴다(요금 확인용)."""
    if profile is None:
        raise ValueError("profile이 필요합니다 — interpret.profile_for(chart)로 만들어 넘기세요.")
    resp = _client().messages.create(
        **build_request(layers, profile, retry_note, model),
        **CREATE_KWARGS,
    )
    u = getattr(resp, "usage", None)
    if u is not None:
        print(f"[usage] in={_n(u, 'input_tokens')} out={_n(u, 'output_tokens')}"
              f" cache_read={_n(u, 'cache_read_input_tokens')}")
    return _extract_text(resp)


class Reply(str):
    """생성문(글자 그대로 str) + 응답이 끝난 이유(stop_reason). 'max_tokens'면 분량 상한에서 끊긴 글,
    'refusal'이면 거절로 끝난 글이다 — run_daily가 이런 글은 보내지 않고 다시 쓰게 한다."""

    def __new__(cls, text: str, stop_reason=None):
        obj = super().__new__(cls, text)
        obj.stop_reason = stop_reason
        return obj


def _extract_text(resp) -> Reply:
    """생각(adaptive thinking)이 켜진 모델은 content 첫 블록이 thinking일 수 있어 text 블록을 골라
    읽는다. 없으면(전면 거절 등) 빈 메시지를 보내는 대신 크게 죽는다(fail-loud)."""
    for block in resp.content:
        if getattr(block, "type", "") == "text":
            return Reply(block.text.strip(), getattr(resp, "stop_reason", None))
    raise RuntimeError(f"응답에 text 블록이 없다 (stop_reason={getattr(resp, 'stop_reason', None)})")
